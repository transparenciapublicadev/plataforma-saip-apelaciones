CREATE TABLE IF NOT EXISTS resoluciones (
    id_resolucion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_apelacion BIGINT NOT NULL REFERENCES apelaciones (id_apelacion),
    id_miembro_ttaip BIGINT REFERENCES miembros_ttaip (id_usuario),
    id_expediente_ttaip BIGINT REFERENCES expedientes_ttaip (id_expediente_ttaip),
    id_sala_ttaip BIGINT REFERENCES salas_ttaip (id_sala_ttaip),
    tipo_resolucion VARCHAR(30) NOT NULL,
    decision VARCHAR(40) NOT NULL,
    fundamentos TEXT NOT NULL,
    fundamento_legal TEXT,
    fecha_resolucion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    numero_resolucion VARCHAR(120) UNIQUE,
    observaciones TEXT,
    causal_fundado VARCHAR(500),
    resultado VARCHAR(60),
    iniciar_proceso_disciplinario BOOLEAN
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_documento_resolucion'
          AND conrelid = 'documentos'::regclass
    ) THEN
        ALTER TABLE documentos
            ADD CONSTRAINT fk_documento_resolucion
            FOREIGN KEY (id_resolucion) REFERENCES resoluciones (id_resolucion)
            DEFERRABLE INITIALLY IMMEDIATE;
    END IF;
END;
$$;

