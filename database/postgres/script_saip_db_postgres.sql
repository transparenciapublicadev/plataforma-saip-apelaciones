CREATE TABLE IF NOT EXISTS solicitudes (
    id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente VARCHAR(50) NOT NULL UNIQUE,
    asunto VARCHAR(500) NOT NULL,
    descripcion TEXT NOT NULL,
    id_ciudadano BIGINT NOT NULL REFERENCES ciudadanos (id_usuario),
    id_entidad BIGINT NOT NULL REFERENCES entidades (id_entidad),
    fecha_presentacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_limite DATE NOT NULL,
