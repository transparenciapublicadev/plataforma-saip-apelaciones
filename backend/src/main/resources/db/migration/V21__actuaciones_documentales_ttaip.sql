CREATE TABLE documentos_preparados_ttaip (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_expediente BIGINT NOT NULL REFERENCES expedientes_ttaip,
    etapa VARCHAR(30) NOT NULL,
    clave VARCHAR(64) NOT NULL,
    decision VARCHAR(40) NOT NULL,
    numero VARCHAR(120),
    id_sala BIGINT REFERENCES salas_ttaip,
    id_documento BIGINT REFERENCES documentos,
    id_resolucion BIGINT REFERENCES resoluciones
);

CREATE UNIQUE INDEX uq_documento_ttaip_en_preparacion
    ON documentos_preparados_ttaip (id_expediente, etapa, clave)
    WHERE id_resolucion IS NULL;

ALTER TABLE resoluciones ADD COLUMN actos_documentales BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE resoluciones ADD COLUMN fecha_validacion_actos TIMESTAMP;
ALTER TABLE cedulas_notificacion ADD COLUMN tipo_acto VARCHAR(20);
ALTER TABLE notificaciones_ttaip ADD COLUMN direccion_destino VARCHAR(500);
ALTER TABLE notificaciones_ttaip ADD COLUMN fecha_eficacia TIMESTAMP;
ALTER TABLE documentos ADD COLUMN borrador_ttaip BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE documentos ADD COLUMN solo_institucional_ttaip BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE suspensiones_plazo_ttaip ADD COLUMN etapa_complementaria VARCHAR(30);
ALTER TABLE suspensiones_plazo_ttaip ADD COLUMN respuesta_complementaria TEXT;
ALTER TABLE suspensiones_plazo_ttaip ADD COLUMN fecha_respuesta_complementaria TIMESTAMP;

CREATE TABLE documentos_informacion_complementaria (
    id_suspension BIGINT NOT NULL REFERENCES suspensiones_plazo_ttaip,
    id_documento BIGINT NOT NULL REFERENCES documentos,
    respuesta BOOLEAN NOT NULL,
    PRIMARY KEY (id_suspension, id_documento)
);
