CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    tipo_usuario VARCHAR(20) NOT NULL,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS entidades (
    id_entidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(200) NOT NULL,
    acronimo VARCHAR(20) NOT NULL UNIQUE,
    descripcion VARCHAR(500),
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    direccion VARCHAR(300),
    telefono VARCHAR(20),
    email VARCHAR(100),
    estado VARCHAR(20)
);

-- Preserve case-insensitive uniqueness without requiring the citext extension.
CREATE UNIQUE INDEX IF NOT EXISTS uq_usuarios_email_lower
    ON usuarios (lower(email));

CREATE UNIQUE INDEX IF NOT EXISTS uq_entidades_acronimo_lower
    ON entidades (lower(acronimo));

