ALTER TABLE documentos ADD COLUMN IF NOT EXISTS id_expediente_ttaip BIGINT;
ALTER TABLE documentos ADD COLUMN IF NOT EXISTS id_cedula BIGINT;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_documento_expediente_ttaip'
          AND conrelid = 'documentos'::regclass
    ) THEN
        ALTER TABLE documentos
            ADD CONSTRAINT fk_documento_expediente_ttaip
            FOREIGN KEY (id_expediente_ttaip)
            REFERENCES expedientes_ttaip (id_expediente_ttaip)
            DEFERRABLE INITIALLY IMMEDIATE;
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_documento_cedula'
          AND conrelid = 'documentos'::regclass
    ) THEN
        ALTER TABLE documentos
            ADD CONSTRAINT fk_documento_cedula
            FOREIGN KEY (id_cedula)
            REFERENCES cedulas_notificacion (id_cedula)
            DEFERRABLE INITIALLY IMMEDIATE;
    END IF;
END;
$$;

