BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_documento_resolucion'
          AND conrelid = 'documentos'::regclass
    ) THEN
        ALTER TABLE documentos
            ADD CONSTRAINT fk_documento_resolucion
            FOREIGN KEY (id_resolucion) REFERENCES resoluciones (id_resolucion)
            DEFERRABLE INITIALLY IMMEDIATE;
    END IF;
END;
$$;

