CREATE TABLE presentaciones_admision_ttaip (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_expediente_ttaip BIGINT NOT NULL REFERENCES expedientes_ttaip (id_expediente_ttaip),
    id_usuario BIGINT NOT NULL REFERENCES usuarios (id_usuario),
    id_descargo BIGINT UNIQUE REFERENCES descargos_entidad_ttaip (id_descargo),
    operacion UUID NOT NULL,
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('DESCARGOS', 'INFORME_ORAL', 'DOCUMENTACION_ADICIONAL')),
    origen VARCHAR(20) NOT NULL CHECK (origen IN ('CIUDADANO', 'ENTIDAD_PUBLICA')),
    texto TEXT,
    numero_oficio VARCHAR(120),
    fecha_presentacion TIMESTAMP NOT NULL,
    aceptada BOOLEAN,
    fecha_respuesta TIMESTAMP,
    operacion_respuesta UUID,
    id_usuario_respuesta BIGINT REFERENCES usuarios (id_usuario),
    UNIQUE (id_expediente_ttaip, operacion),
    CHECK ((tipo = 'DESCARGOS') = (id_descargo IS NOT NULL))
);

ALTER TABLE documentos
    ADD COLUMN id_presentacion_admision BIGINT REFERENCES presentaciones_admision_ttaip (id),
    ADD COLUMN clase_adjunto_admision VARCHAR(10);

CREATE INDEX idx_documentos_presentacion_admision ON documentos (id_presentacion_admision)
    WHERE id_presentacion_admision IS NOT NULL;
