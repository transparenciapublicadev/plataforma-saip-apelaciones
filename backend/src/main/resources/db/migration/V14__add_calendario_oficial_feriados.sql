-- 1. Tabla de feriados, días no laborables y suspensiones institucionales
CREATE TABLE IF NOT EXISTS calendario_feriado (
    id VARCHAR(100) PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    tipo VARCHAR(30) NOT NULL DEFAULT 'feriado',
    recurrente BOOLEAN NOT NULL DEFAULT FALSE,
    mmdd VARCHAR(10),
    fecha DATE,
    hasta DATE,
    base_legal VARCHAR(255),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    origen VARCHAR(20) NOT NULL DEFAULT 'sistema',
    alcance_nacional BOOLEAN NOT NULL DEFAULT TRUE,
    entidades_ids TEXT,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_calendario_feriado_activo ON calendario_feriado(activo);
CREATE INDEX IF NOT EXISTS idx_calendario_feriado_fecha ON calendario_feriado(fecha);
CREATE INDEX IF NOT EXISTS idx_calendario_feriado_recurrente ON calendario_feriado(recurrente, mmdd);

-- 2. Tabla de auditoría de cambios del calendario oficial
CREATE TABLE IF NOT EXISTS calendario_historial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario VARCHAR(100),
    detalle TEXT NOT NULL,
    norma VARCHAR(255)
);

